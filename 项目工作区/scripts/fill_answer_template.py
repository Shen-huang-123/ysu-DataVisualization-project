def put(i, text, bold=False):
    p[i].text = text
    p[i].style = d.styles['Normal']
    for run in p[i].runs:
        run.font.name = 'Microsoft YaHei'
        run.font.size = Pt(10.5)
        run.font.color.rgb = RGBColor(28, 53, 59)
        run.bold = bold
    p[i].paragraph_format.space_after = Pt(5)

def fig(i, rel, caption):
    img = ROOT / rel
    assert img.exists(), img
    p[i].text = ''
    r = p[i].add_run()
    r.add_picture(str(img), width=Cm(13.5))
    p[i].alignment = WD_ALIGN_PARAGRAPH.CENTER
    p[i].add_run('\n' + caption).italic = True
    p[i].paragraph_format.space_after = Pt(8)

def clear(i):
    p[i].text = ''

